"""Generates lib/presentation/body_map/body_map_data.dart.

Source: react-native-body-highlighter by ELABBASSI Hicham (MIT licence),
https://github.com/HichamELBSI/react-native-body-highlighter
Pass the folder that holds its assets/bodyFront.ts, assets/bodyBack.ts and
components/SvgMaleWrapper.tsx (flattened into one folder is fine):

    python tool/gen_body_map.py <source-folder>
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "lib" / "presentation" / "body_map" / "body_map_data.dart"


def find(src: pathlib.Path, name: str) -> pathlib.Path:
    hits = list(src.rglob(name))
    if not hits:
        sys.exit(f"missing {name} under {src}")
    return hits[0]


def parts(ts: str) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    marks = [(m.start(), m.group(1)) for m in re.finditer(r'slug:\s*"([a-z-]+)"', ts)]
    for i, (pos, slug) in enumerate(marks):
        end = marks[i + 1][0] if i + 1 < len(marks) else len(ts)
        out.setdefault(slug, []).extend(re.findall(r'"([Mm][^"]+)"', ts[pos:end]))
    return out


def outlines(tsx: str) -> list[str]:
    return re.findall(r'd="(M[^"]+)"', tsx)


def dart_map(name: str, data: dict[str, list[str]]) -> str:
    lines = [f"const {name} = <String, List<String>>{{"]
    for slug, paths in data.items():
        lines.append(f"  '{slug}': [")
        lines.extend(f"    '{p}'," for p in paths)
        lines.append("  ],")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = pathlib.Path(sys.argv[1])
    front = parts(find(src, "bodyFront.ts").read_text(encoding="utf-8"))
    back = parts(find(src, "bodyBack.ts").read_text(encoding="utf-8"))
    front_outline, back_outline = outlines(find(src, "SvgMaleWrapper.tsx").read_text(encoding="utf-8"))[:2]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "\n\n".join(
            [
                "// GENERATED by tool/gen_body_map.py - do not edit.\n"
                "//\n"
                "// Body outline and muscle paths from react-native-body-highlighter\n"
                "// Copyright (c) 2022 ELABBASSI Hicham, MIT licence.\n"
                "// Coordinates: front in x 0..724, back in x 724..1448, y 0..1448.\n"
                "// ignore_for_file: lines_longer_than_80_chars",
                dart_map("bodyFrontParts", front),
                dart_map("bodyBackParts", back),
                f"const bodyFrontOutline = '{front_outline}';",
                f"const bodyBackOutline = '{back_outline}';",
            ]
        )
        + "\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)}: {len(front)} front parts, {len(back)} back parts")


if __name__ == "__main__":
    main()
